// Given the (row, col) of the cell the person picked, returns the
// verified answer for that position's residue class.
export function getAnswerForCell(row, col) {
  const flatIndex = row * COLS + col;
  const residue = flatIndex % 9;
  return RAM_SHALAKA_ANSWERS[residue];
}
