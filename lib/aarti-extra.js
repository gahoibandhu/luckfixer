const couplets = (rows) => {            // [[half1, half2], ...] -> stanzas of two couplets (4 lines), half-lines end with । and ॥
  const lines = rows.flatMap(([a, b]) => [`${a}।`, `${b}॥`]);
  const out = []; for (let i = 0; i < lines.length; i += 4) out.push(lines.slice(i, i + 4));
  return out;
};
