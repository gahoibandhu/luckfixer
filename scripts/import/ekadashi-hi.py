#!/usr/bin/env python3
"""Reads scripts/import/24_Ekadashi_Vrat_Katha_Hindi.txt and writes lib/ekadashi-hi.js (Hindi katha, sandesh, prarthana per Ekadashi).
Run from the project root:  python3 scripts/import/ekadashi-hi.py
Edit the .txt and re-run to update the site text. Headings must stay in the form  "N. <naam> एकादशी व्रत कथा"  between ==== lines."""
import re, json, sys, pathlib
SRC = pathlib.Path('scripts/import/24_Ekadashi_Vrat_Katha_Hindi.txt'); OUT = pathlib.Path('lib/ekadashi-hi.js')
SLUG = {'उत्पन्ना': 'utpanna', 'मोक्षदा': 'mokshada', 'सफला': 'saphala', 'पुत्रदा': 'pausha-putrada', 'षटतिला': 'shattila', 'जया': 'jaya',
        'विजया': 'vijaya', 'आमलकी': 'amalaki', 'पापमोचनी': 'papmochani', 'कामदा': 'kamada', 'वरुथिनी': 'varuthini', 'मोहिनी': 'mohini',
        'अपरा': 'apara', 'निर्जला': 'nirjala', 'योगिनी': 'yogini', 'देवशयनी': 'devshayani', 'कामिका': 'kamika', 'श्रावण पुत्रदा': 'shravana-putrada',
        'अजा': 'aja', 'परिवर्तिनी': 'parivartini', 'इंदिरा': 'indira', 'पापांकुशा': 'papankusha', 'रमा': 'rama', 'देवउठनी': 'devutthana'}
t = SRC.read_text(encoding='utf-8')
parts = re.split(r'\n={20,}\n(\d+)\. (.+?)\n={20,}\n', t)
out, general = {}, None
for i in range(1, len(parts), 3):
    title = re.sub(r'\s*एकादशी व्रत कथा\s*$', '', parts[i + 1].strip()).split(' / ')[0].strip()
    slug = SLUG.get(title)
    if not slug: print('UNKNOWN heading, skipped:', title); continue
    body = parts[i + 2]
    body = body.split('\n====')[0]                                   # the last section is followed by the general prayer block
    paras = [p.strip() for p in body.split('\n\n') if p.strip()]
    pray = next((p for p in paras if p.startswith('प्रार्थना')), '')
    rest = [p for p in paras if p != pray]
    msg = next((p for p in rest if 'संदेश है' in p), '')
    if not msg and rest: msg = ''                                     # no explicit message paragraph (e.g. Indira): keep everything as katha
    katha = [p for p in rest if p != msg]
    out[slug] = {'katha': katha, 'msg': msg, 'pray': re.sub(r'^प्रार्थना:\s*', '', pray)}
m = re.search(r'एकादशी की सामान्य पूजा के लिए सरल प्रार्थना\n={20,}\n\n(.+?)\n\nसमापन', t, re.S)
general = [l.strip() for l in m.group(1).split('\n') if l.strip()] if m else []
missing = sorted(set(SLUG.values()) - set(out))
OUT.write_text('// GENERATED by scripts/import/ekadashi-hi.py from 24_Ekadashi_Vrat_Katha_Hindi.txt — edit the .txt and re-run, do not edit here.\n'
               'export const EKADASHI_HI = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
               'export const EKADASHI_GENERAL_PRAYER = ' + json.dumps(general, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')
print('wrote', OUT, '| sections', len(out), '| missing', missing, '| general prayer lines', len(general))
